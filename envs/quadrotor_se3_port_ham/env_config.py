"""Config-file + command-line plumbing for the SE(3) quadrotor environment.

Resolution order (later wins):

    quadrotor_se3.__init__ defaults   <   YAML config file   <   CLI flags / kwargs

The CLI flags are generated by *reflecting over* ``quadrotor_se3.__init__``, so
adding an argument to the env automatically makes it configurable and
overridable — there is no hand-maintained list of parameter names in this file.

Command-line use (any config value can be overridden)::

    python envs/quadrotor_se3_port_ham/quadrotor.py \
        --config configs/quadrotor_se3/envs/sde.yaml \
        --external_force_type random --wind_force_std 0.8

Programmatic use::

    env = quadrotor_se3.from_config("configs/quadrotor_se3/envs/ode.yaml")
    env = quadrotor_se3.from_config("configs/.../sde.yaml", seed=7)   # kwargs win

Inspect what a config + flags actually resolve to, without building anything::

    python envs/quadrotor_se3_port_ham/env_config.py \
        --config configs/quadrotor_se3/envs/sde.yaml --wind_force_std 0.8
"""
from __future__ import annotations

import argparse
import os
import sys
import typing

_THIS_DIR = os.path.dirname(os.path.abspath(__file__))
if _THIS_DIR not in sys.path:
    sys.path.insert(0, _THIS_DIR)

from quadrotor import quadrotor_se3  # noqa: E402

PROJECT_ROOT = os.path.abspath(os.path.join(_THIS_DIR, "..", ".."))
CONFIG_DIR = os.path.join(PROJECT_ROOT, "configs", "quadrotor_se3", "envs")
ODE_CONFIG = os.path.join(CONFIG_DIR, "ode.yaml")
SDE_CONFIG = os.path.join(CONFIG_DIR, "sde.yaml")

# Enumerated arguments the env itself validates.  Listing them here only moves
# the error earlier (argparse instead of a ValueError at construction time).
CHOICES = {
    "external_force_type": ["sine", "square", "random", "constant"],
    "render_backend": ["pybullet", "matplotlib"],
    "render_mode": ["human", "rgb_array"],
    "ori_rep": ["rotmat"],
}

